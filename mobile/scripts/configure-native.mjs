import { writeFile } from 'node:fs/promises';

const apiUrl = (process.env.MOBILE_API_URL ?? 'http://10.0.2.2:8087/api').replace(/\/$/, '');
const url = new URL(apiUrl);
if (!['https:', 'http:'].includes(url.protocol) || url.username || url.password ||
    url.search || url.hash || url.pathname !== '/api') {
  throw new Error('MOBILE_API_URL must be an HTTP(S) URL ending with /api, without credentials or query parameters.');
}
if (process.env.MOBILE_RELEASE === 'true' && url.protocol !== 'https:') {
  throw new Error('Release builds require an HTTPS API URL.');
}
await writeFile(new URL('../src/environments/environment.native.ts', import.meta.url),
  `// Generated by scripts/configure-native.mjs; do not commit.\nexport const environment = ${JSON.stringify({ apiUrl })};\n`);
console.log(`Android API: ${apiUrl}`);
